local function _cloneArray(list)
	local out = {}
	for i, v in ipairs(list) do
		out[i] = v
	end
	return out
end

local function _addUnique(target, value, seen)
	if value == nil or value == "" then
		return
	end
	if seen[value] then
		return
	end
	seen[value] = true
	table.insert(target, value)
end

function H.getFirstCharacter(text: string): string
	if text == "" then
		return ""
	end
	local first = ""
	for s, e in utf8.graphemes(text) do
		first = string.sub(text, s, e)
		break
	end
	return first
end

function H.getLastCharacter(text: string): string
	if text == "" then
		return ""
	end
	local last = ""
	for s, e in utf8.graphemes(text) do
		last = string.sub(text, s, e)
	end
	return last
end

function H.flatten()
	local out = {}
	local seen = {}
	for _, list in pairs(H.groups) do
		for _, word in ipairs(list) do
			_addUnique(out, word, seen)
		end
	end
	for _, word in ipairs(H.special) do
		_addUnique(out, word, seen)
	end
	return out
end

function H.buildIndex()
	local idx = {
		all = {},
		byFirst = {},
		byLast = {},
		special = {},
		priority = {},
	}

	local seen = {}

	local function ingest(word: string, isSpecial: boolean)
		if word == nil or word == "" then
			return
		end

		if seen[word] then
			if isSpecial then
				idx.priority[word] = true
			end
			return
		end

		seen[word] = true
		table.insert(idx.all, word)

		local first = H.getFirstCharacter(word)
		local last = H.getLastCharacter(word)

		if first ~= "" then
			idx.byFirst[first] = idx.byFirst[first] or {}
			table.insert(idx.byFirst[first], word)
		end

		if last ~= "" then
			idx.byLast[last] = idx.byLast[last] or {}
			table.insert(idx.byLast[last], word)
		end

		if isSpecial then
			idx.special[word] = true
			idx.priority[word] = true
		end
	end

	for _, list in pairs(H.groups) do
		for _, word in ipairs(list) do
			ingest(word, false)
		end
	end

	for _, word in ipairs(H.special) do
		ingest(word, true)
	end

	return idx
end

H.index = H.buildIndex()

function H.getGroup(key: string)
	return H.groups[key] or {}
end

function H.getByLast(key: string)
	return H.index.byLast[key] or {}
end

function H.getByFirst(key: string)
	return H.index.byFirst[key] or {}
end

function H.isPriority(word: string): boolean
	return H.priority[word] == true
end

function H.getStats()
	local groupCount = 0
	local wordCount = 0

	for _, list in pairs(H.groups) do
		groupCount += 1
		wordCount += #list
	end

	return {
		version = H.version,
		title = H.title,
		groups = groupCount,
		words = wordCount,
		special = #H.special,
		unique = #H.index.all,
		priority = 0, -- backward-safe field
	}
end

return H
